// Convert a planner export (tools/swept_area.html → "Export path (JSON)") into
// the C header the cleaner firmware includes.
// usage: node tools/plan-to-header.mjs <plan.json> <out.h>
import { readFileSync, writeFileSync } from "node:fs";

const [IN, OUT] = process.argv.slice(2);
if (!IN || !OUT) {
  console.error("usage: node tools/plan-to-header.mjs <plan.json> <out.h>");
  process.exit(1);
}

const plan = JSON.parse(readFileSync(IN, "utf8"));
const { arcs, park, metrics, config, rings } = plan;
if (!Array.isArray(arcs) || !arcs.length) {
  console.error("plan has no arcs — export from the tool with the current planner");
  process.exit(1);
}

const rows = arcs.map(
  (a) => `  { ${a.ring}, ${Math.round(a.r * 10)}, ${Math.round(a.t1a * 10)}, ${Math.round(a.t1b * 10)}, ${Math.round(a.t2 * 10)} }`,
);

const header = `/* Generated by tools/plan-to-header.mjs — do not edit by hand.
   Source: tools/swept_area.html planner (open-loop export: arcs, not poses)
   brush ${config.brushCm} cm · overlap ${config.overlapCm} cm · rings ${rings.join(" / ")} cm
   ${arcs.length} arcs · planner travel ${metrics.travelDeg} deg (assumes 45 deg/s and position feedback)
   park (${park.t1}, ${park.t2}) deg

   Each arc is executable without feedback: the elbow holds one angle while the
   shoulder sweeps t1a -> t1b, so the move is "elbow to t2, shoulder to t1a,
   sweep to t1b" with the brush on. Re-home between rings to bound drift. */

#pragma once
#include <stdint.h>

struct CleanArc {
  uint8_t ring;    // 1..3 — re-home when this changes
  int16_t radius;  // tenths of a cm (informational)
  int16_t t1a;     // shoulder start, tenths of a degree
  int16_t t1b;     // shoulder end, tenths of a degree
  int16_t t2;      // elbow hold, tenths of a degree
};

#define ARC_COUNT ${arcs.length}u
#define ARC_RINGS ${rings.length}u
#define PARK_T1 ${Math.round(park.t1 * 10)}
#define PARK_T2 ${Math.round(park.t2 * 10)}

static const CleanArc ARCS[ARC_COUNT] PROGMEM = {
${rows.join(",\n")}
};
`;

writeFileSync(OUT, header);
console.log(`arcs: ${arcs.length} across ${rings.length} rings → ${OUT}`);
for (const a of arcs) console.log(`  ring ${a.ring}  r=${a.r}  shoulder ${a.t1a}→${a.t1b}  elbow ${a.t2}`);
